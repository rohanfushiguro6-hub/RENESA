-- RENESA starter schema. Run in Supabase Dashboard > SQL Editor.
create table if not exists public.products (
 id bigint generated by default as identity primary key,
 created_at timestamptz not null default now(),
 name text not null,
 description text not null default '',
 price numeric(12,2) not null check(price >= 0),
 old_price numeric(12,2) check(old_price is null or old_price >= 0),
 image_url text not null default '',
 category text not null default 'অন্যান্য',
 stock integer not null default 0 check(stock >= 0),
 is_active boolean not null default true
);
create table if not exists public.orders (
 id bigint generated by default as identity primary key,
 created_at timestamptz not null default now(),
 customer_name text not null check(char_length(customer_name) between 1 and 100),
 phone text not null check(char_length(phone) between 5 and 25),
 address text not null check(char_length(address) between 5 and 500),
 note text not null default '', items jsonb not null,
 total numeric(12,2) not null check(total >= 0),
 status text not null default 'pending' check(status in ('pending','confirmed','processing','shipped','delivered','cancelled')),
 payment_method text not null default 'COD' check(payment_method='COD')
);
create table if not exists public.admin_users (
 user_id uuid primary key references auth.users(id) on delete cascade,
 created_at timestamptz not null default now()
);
alter table public.products enable row level security;
alter table public.orders enable row level security;
alter table public.admin_users enable row level security;
grant select on public.products to anon, authenticated;
grant insert,update,delete on public.products to authenticated;
grant insert on public.orders to anon,authenticated;
grant select,update on public.orders to authenticated;
grant select on public.admin_users to authenticated;
grant usage,select on sequence public.products_id_seq to anon,authenticated;
grant usage,select on sequence public.orders_id_seq to anon,authenticated;
-- Public catalog reads; inactive products visible only to admins.
drop policy if exists "Products visible" on public.products;
create policy "Products visible" on public.products for select to anon,authenticated using (is_active=true or exists(select 1 from public.admin_users a where a.user_id=auth.uid()));
drop policy if exists "Admin insert products" on public.products;
create policy "Admin insert products" on public.products for insert to authenticated with check(exists(select 1 from public.admin_users a where a.user_id=auth.uid()));
drop policy if exists "Admin update products" on public.products;
create policy "Admin update products" on public.products for update to authenticated using(exists(select 1 from public.admin_users a where a.user_id=auth.uid())) with check(exists(select 1 from public.admin_users a where a.user_id=auth.uid()));
drop policy if exists "Admin delete products" on public.products;
create policy "Admin delete products" on public.products for delete to authenticated using(exists(select 1 from public.admin_users a where a.user_id=auth.uid()));
-- Anyone can submit COD orders. Only admins can read/update orders.
drop policy if exists "Public submit orders" on public.orders;
create policy "Public submit orders" on public.orders for insert to anon,authenticated with check(char_length(customer_name) between 1 and 100 and char_length(phone) between 5 and 25 and char_length(address) between 5 and 500 and total>=0 and payment_method='COD');
drop policy if exists "Admins read orders" on public.orders;
create policy "Admins read orders" on public.orders for select to authenticated using(exists(select 1 from public.admin_users a where a.user_id=auth.uid()));
drop policy if exists "Admins update orders" on public.orders;
create policy "Admins update orders" on public.orders for update to authenticated using(exists(select 1 from public.admin_users a where a.user_id=auth.uid())) with check(exists(select 1 from public.admin_users a where a.user_id=auth.uid()));
drop policy if exists "Admin sees own row" on public.admin_users;
create policy "Admin sees own row" on public.admin_users for select to authenticated using(user_id=auth.uid());
-- Product photo storage bucket (public read, admin-only uploads).
insert into storage.buckets(id,name,public) values('renesa-products','renesa-products',true) on conflict(id) do update set public=true;
drop policy if exists "Public view product images" on storage.objects;
create policy "Public view product images" on storage.objects for select to anon,authenticated using(bucket_id='renesa-products');
drop policy if exists "Admin upload product images" on storage.objects;
create policy "Admin upload product images" on storage.objects for insert to authenticated with check(bucket_id='renesa-products' and exists(select 1 from public.admin_users a where a.user_id=auth.uid()));
drop policy if exists "Admin update product images" on storage.objects;
create policy "Admin update product images" on storage.objects for update to authenticated using(bucket_id='renesa-products' and exists(select 1 from public.admin_users a where a.user_id=auth.uid())) with check(bucket_id='renesa-products' and exists(select 1 from public.admin_users a where a.user_id=auth.uid()));
drop policy if exists "Admin delete product images" on storage.objects;
create policy "Admin delete product images" on storage.objects for delete to authenticated using(bucket_id='renesa-products' and exists(select 1 from public.admin_users a where a.user_id=auth.uid()));
